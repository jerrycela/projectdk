// 找出起點位置
export function findSpawnPoint(map) {
  for (let y = 0; y < map.length; y++) {
    const x = map[y].indexOf('S');
    if (x !== -1) {
      return { x, y };
    }
  }
  return null;
}

// 找出終點位置
export function findExitPoint(map) {
  for (let y = 0; y < map.length; y++) {
    const x = map[y].indexOf('E');
    if (x !== -1) {
      return { x, y };
    }
  }
  return null;
}
